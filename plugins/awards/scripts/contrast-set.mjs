#!/usr/bin/env node
// The contrast set: which habits separate the corpus's winners from pages that won nothing. Every card is a winner
// or a nominee, so the corpus alone can say what winners do but not which of those habits are the genre's and which
// are any page's. This runs the same rendered audit on the cards' live URLs and on a queue of unawarded pages
// (template demos, launches), keeps only which rules fired (measurements, never the pages), and tabulates each
// rule's prevalence in both groups. Owner policy first: a refused site is skipped, never retried.
// Usage: node scripts/contrast-set.mjs [--queue references/sites/_contrast-queue.md] [--winners slug,slug|all]
//        [--limit <n per group>] [--table-only] [--json]
// Writes references/sites/_prevalence.json (one row per URL) and references/sites/_prevalence.md (the table).
// Exit: 0 · 1 usage · 3 browser unavailable.
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseArgs } from './lib/report.mjs';
import { cardFiles } from './lib/cards.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const sitesDir = path.join(here, '..', 'references', 'sites');
const RULES = JSON.parse(fs.readFileSync(path.join(here, 'data/rules.json'), 'utf8'));
const args = parseArgs(process.argv.slice(2), { json: 'boolean', 'table-only': 'boolean' });
const dataFile = path.join(sitesDir, '_prevalence.json');
const tableFile = path.join(sitesDir, '_prevalence.md');
const data = (() => { try { return JSON.parse(fs.readFileSync(dataFile, 'utf8')); } catch { return { runs: {} }; } })();

const run = (script, argv, ms) => new Promise((resolve) => {
  const child = spawn(process.execPath, [path.join(here, script), ...argv], { stdio: ['ignore', 'pipe', 'pipe'] });
  let out = '', err = '';
  const timer = setTimeout(() => child.kill('SIGKILL'), ms);
  child.stdout.on('data', (d) => { out += d; });
  child.stderr.on('data', (d) => { err += d; });
  child.on('exit', (code) => { clearTimeout(timer); resolve({ code: code ?? 1, out, err }); });
});

async function measure(url, group, slug) {
  const policy = await run('policy.mjs', [url], 60000);
  if (policy.code === 2) return { group, slug, status: 'refused by the owner\'s policy' };
  if (policy.code === 4) return { group, slug, status: 'unreachable' };
  const audit = await run('audit.mjs', [url, '--render', '--json', '--no-write'], 600000);
  if (audit.code === 3) { console.error('the rendered audit needs Playwright and Chromium'); process.exit(3); }
  try {
    const report = JSON.parse(audit.out);
    // A page whose rendered steps failed says nothing about its habits.
    if (report.findings.filter((f) => f.rule === 'ERR').length >= 3) return { group, slug, status: 'not measured: the rendered steps failed' };
    return { group, slug, status: 'measured', rules: [...new Set(report.findings.filter((f) => f.rule !== 'ERR').map((f) => f.rule))].sort() };
  } catch {
    return { group, slug, status: `not measured: ${(audit.err || 'no report').split('\n')[0].slice(0, 100)}` };
  }
}

function table() {
  const rows = Object.entries(data.runs).filter(([, r]) => r.status === 'measured');
  const groups = { winner: rows.filter(([, r]) => r.group === 'winner'), contrast: rows.filter(([, r]) => r.group === 'contrast') };
  const share = (list, id) => (list.length ? list.filter(([, r]) => r.rules.includes(id)).length / list.length : 0);
  const ids = [...new Set(rows.flatMap(([, r]) => r.rules))].filter((id) => RULES[id]);
  const lines = ids.map((id) => ({ id, w: share(groups.winner, id), c: share(groups.contrast, id) })).sort((a, b) => (b.c - b.w) - (a.c - a.w) || a.id.localeCompare(b.id));
  const pct = (x) => `${Math.round(x * 100)} %`;
  const out = [
    '# Prevalence: winners against unawarded pages',
    '',
    '<!-- generated by scripts/contrast-set.mjs from _prevalence.json; do not edit by hand -->',
    '',
    `Which audit rules fire on the corpus's live pages and on a contrast group of unawarded pages (template demos and launches, listed in \`_contrast-queue.md\`), measured with \`audit.mjs <url> --render\` at desktop, tablet and phone. A rule far more common in the contrast group is a habit that separates; one equally common in both is the genre's, whatever its slop-scan row says. Measured pages: ${groups.winner.length} winners, ${groups.contrast.length} unawarded. With groups this small, read a difference under about 25 points as noise. The contrast group leans to SaaS templates, so it says most about the template and category ruts.`,
    '',
    '| Rule | What it catches | Winners | Unawarded | Difference |',
    '|---|---|---|---|---|',
    ...lines.map((l) => `| ${l.id} | ${RULES[l.id].message.replace(/\|/g, '/')} | ${pct(l.w)} | ${pct(l.c)} | ${l.c - l.w >= 0 ? '+' : ''}${Math.round((l.c - l.w) * 100)} |`),
    '',
    '## Pages',
    '',
    '| URL | Group | Status |',
    '|---|---|---|',
    ...Object.entries(data.runs).sort(([a], [b]) => a.localeCompare(b)).map(([url, r]) => `| ${url} | ${r.group}${r.slug ? ` ([site:${r.slug}])` : ''} | ${r.status}${r.date ? `, ${r.date}` : ''} |`),
    '',
  ];
  return out.join('\n');
}

if (!args['table-only']) {
  const limit = Number(args.limit ?? 8);
  const queueFile = path.resolve(String(args.queue ?? path.join(sitesDir, '_contrast-queue.md')));
  const contrast = fs.existsSync(queueFile) ? [...fs.readFileSync(queueFile, 'utf8').matchAll(/^- (https?:\/\/\S+)/gm)].map((m) => m[1]).slice(0, limit) : [];
  const wanted = args.winners && args.winners !== true && args.winners !== 'all' ? new Set(String(args.winners).split(',')) : null;
  const winners = cardFiles(sitesDir).map((f) => ({ slug: path.basename(f, '.md'), url: fs.readFileSync(f, 'utf8').match(/^# .+? — (https?:\/\/\S+)/m)?.[1] }))
    .filter((c) => c.url && c.slug !== 'floema-jewelry' && (!wanted || wanted.has(c.slug))).slice(0, wanted ? Infinity : limit);
  for (const [group, list] of [['contrast', contrast.map((url) => ({ url }))], ['winner', winners]]) {
    for (const { url, slug } of list) {
      if (data.runs[url]?.status === 'measured') continue;
      process.stderr.write(`${group} ${url} … `);
      const r = await measure(url, group, slug);
      data.runs[url] = { ...r, date: new Date().toISOString().slice(0, 10) };
      process.stderr.write(`${r.status}\n`);
      fs.writeFileSync(dataFile, JSON.stringify(data, null, 2) + '\n');
    }
  }
}
const md = table();
fs.writeFileSync(tableFile, md);
if (args.json) console.log(JSON.stringify(data, null, 2));
else console.log(`wrote ${path.relative(process.cwd(), tableFile)} (${Object.values(data.runs).filter((r) => r.status === 'measured').length} measured pages)`);
