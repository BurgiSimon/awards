#!/usr/bin/env node
// The recipe catalogue in recipes/README.md, generated from every recipe.json so the table cannot drift from
// the data: one section per group (scripts/data/recipe-tags.json), rows by tier then id, the Seen in column
// straight from seenIn. Also enforces the tag vocabulary: every tag in one facet, no retired spelling.
// Usage: node scripts/build-catalogue.mjs [--check]   Exit: 0 written or in sync · 1 drift or a bad recipe.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from './lib/report.mjs';

const plugin = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const recipes = path.join(plugin, 'recipes');
const readmeFile = path.join(recipes, 'README.md');
const START = '<!-- catalogue:start (generated by scripts/build-catalogue.mjs; edit recipe.json, not this table) -->';
const END = '<!-- catalogue:end -->';

export function catalogue() {
  const vocab = JSON.parse(fs.readFileSync(path.join(plugin, 'scripts/data/recipe-tags.json'), 'utf8'));
  const facetOf = new Map(Object.entries(vocab.facets).flatMap(([facet, tags]) => tags.map((t) => [t, facet])));
  const problems = [];
  const entries = fs.readdirSync(recipes).filter((d) => fs.existsSync(path.join(recipes, d, 'recipe.json'))).map((id) => {
    const j = JSON.parse(fs.readFileSync(path.join(recipes, id, 'recipe.json'), 'utf8'));
    if (j.id !== id) problems.push(`${id}: id is ${j.id}`);
    for (const key of ['intent', 'group', 'summary']) if (!j[key]) problems.push(`${id}: no ${key}`);
    if (j.group && !vocab.groups[j.group]) problems.push(`${id}: unknown group ${j.group}`);
    if (j.added !== undefined && !/^\d{4}-\d{2}-\d{2}$/.test(String(j.added))) problems.push(`${id}: added is ${j.added}, not YYYY-MM-DD`);
    for (const t of j.tags ?? []) {
      if (t in vocab.aliases) problems.push(`${id}: retired tag ${t}${vocab.aliases[t] ? ` (use ${vocab.aliases[t]})` : ''}`);
      else if (!facetOf.has(t)) problems.push(`${id}: tag ${t} is not in scripts/data/recipe-tags.json`);
    }
    return j;
  });
  const used = new Set(entries.flatMap((e) => e.tags ?? []));
  for (const t of facetOf.keys()) if (!used.has(t)) problems.push(`vocabulary: ${t} is used by no recipe`);

  const cell = (s) => String(s).replace(/\|/g, '\\|');
  const seen = (e) => {
    const sites = (e.seenIn ?? []).join(', ');
    const frames = e.visuals ? 'synthetic example, frames in `recipe.json.visuals`' : '';
    return [sites, frames].filter(Boolean).join('; ') || '—';
  };
  const sections = Object.entries(vocab.groups).map(([key, g]) => {
    const rows = entries.filter((e) => e.group === key).sort((a, b) => a.tier.localeCompare(b.tier) || a.id.localeCompare(b.id));
    if (!rows.length) return '';
    const see = g.pattern ? ` See \`[pattern:${g.pattern}]\`.` : '';
    return `### ${g.title}\n\n${g.about[0].toUpperCase()}${g.about.slice(1)}.${see}\n\n| Intent | Recipe | Tier | Demonstrates | Seen in |\n|---|---|---|---|---|\n${rows.map((e) => `| ${cell(e.intent)} | \`${e.id}\` | ${e.tier} | ${cell(e.summary)} | ${cell(seen(e))} |`).join('\n')}\n`;
  }).filter(Boolean);
  const facets = Object.entries(vocab.facets).map(([facet, tags]) => `- ${facet}: ${tags.map((t) => `\`${t}\``).join(' ')}`).join('\n');
  const body = `${START}\n${sections.join('\n')}\n### Tags\n\nEvery tag in a \`recipe.json\` comes from one facet of \`scripts/data/recipe-tags.json\`:\n\n${facets}\n${END}`;
  return { body, problems, count: entries.length, compositions: entries.filter((e) => e.id.startsWith('complete-')).length };
}

// The count sentence above the table ("has 102 entries: 101 focused recipes and one complete composition"), restated
// from the same files so a new recipe cannot leave it behind.
const restate = (text, count, compositions) => text.replace(
  /\bhas \d+ entries: \d+ focused recipes and (?:one|\d+) complete compositions?/,
  `has ${count} entries: ${count - compositions} focused recipes and ${compositions === 1 ? 'one complete composition' : `${compositions} complete compositions`}`,
);

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = parseArgs(process.argv.slice(2), { check: 'boolean' });
  const { body, problems, count, compositions } = catalogue();
  const readme = fs.readFileSync(readmeFile, 'utf8');
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < 0) { console.error(`recipes/README.md has no ${START.slice(0, 22)}… / ${END} markers`); process.exit(1); }
  const next = restate(readme.slice(0, a), count, compositions) + body + readme.slice(b + END.length);
  for (const p of problems) console.error(`  ${p}`);
  if (args.check) {
    const drift = next !== readme;
    if (drift) console.error('recipes/README.md catalogue is out of date: run node scripts/build-catalogue.mjs');
    console.log(`${count} recipe(s) · ${problems.length} problem(s) · table ${drift ? 'stale' : 'in sync'}`);
    process.exit(drift || problems.length ? 1 : 0);
  }
  fs.writeFileSync(readmeFile, next);
  console.log(`${count} recipe(s) → recipes/README.md · ${problems.length} problem(s)`);
  process.exit(problems.length ? 1 : 0);
}
