#!/usr/bin/env node
// The corpus index table in references/sites/_index.md (or a project's .awards/sites/_index.md), built from
// every card's header so a row can never disagree with its card: canonical class, industry, routes read,
// visitor mode, narrative, WebGL dosage, scroll model, and the one-line palette, type, award, confidence and
// date rows each card carries for the index. Everything outside the markers is kept as written.
// Usage: node scripts/build-index.mjs [--dir <sites dir>] [--check]   Exit: 0 written or in sync · 1 drift.
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs } from './lib/report.mjs';
import { cardFiles, parseCard, firstClause, canonicalClass, pluginSites } from './lib/cards.mjs';

const args = parseArgs(process.argv.slice(2), { check: 'boolean' });
const dir = path.resolve(String(args.dir ?? pluginSites));
const file = path.join(dir, '_index.md');
const START = '<!-- index:start (generated by scripts/build-index.mjs from the card headers; edit the cards) -->';
const END = '<!-- index:end -->';
const COLUMNS = ['Slug', 'Site', 'Class', 'Industry', 'Routes', 'Visitor mode', 'Narrative model', 'WebGL dosage', 'Scroll model', 'Palette strategy', 'Type contract', 'Awards / score', 'Confidence', 'Last verified'];

const cell = (s) => String(s ?? '—').replace(/(?<!\\)\|/g, '\\|') || '—';
const rows = cardFiles(dir).map(parseCard).map((c) => {
  const h = c.header;
  return [`\`${c.slug}\``, c.site, canonicalClass(h.Class) ?? `${firstClause(h.Class)} (unclassed)`, h.Industry, c.route, firstClause(h['Visitor mode']),
    firstClause(h['Narrative model']), firstClause(h['WebGL dosage']), firstClause(h['Scroll model']), h['Palette strategy'], h['Type contract'],
    h['Awards / score'], h.Confidence, h['Last verified']].map(cell);
});
const table = `${START}\n| ${COLUMNS.join(' | ')} |\n|${COLUMNS.map(() => '---').join('|')}|\n${rows.map((r) => `| ${r.join(' | ')} |`).join('\n')}\n${END}`;

let doc = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : `# Project corpus index\n\nProject-local cards written by \`awards:research\`, read alongside the plugin corpus.\n\n${START}\n${END}\n`;
const a = doc.indexOf(START), b = doc.indexOf(END);
if (a < 0 || b < 0) { console.error(`${path.relative(process.cwd(), file)} has no index markers`); process.exit(1); }
const next = doc.slice(0, a) + table + doc.slice(b + END.length);
if (args.check) {
  const ok = next === doc;
  console.log(`${rows.length} card(s) · index ${ok ? 'in sync' : 'stale: run node scripts/build-index.mjs'}`);
  process.exit(ok ? 0 : 1);
}
fs.writeFileSync(file, next);
console.log(`${rows.length} card(s) → ${path.relative(process.cwd(), file)}`);
